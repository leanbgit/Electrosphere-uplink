#!/usr/bin/env python3
"""
gen_hle_table.py -- dispatch table for the interpreter-only build.

Writes a C file with ac3_func_table[] holding ONLY the Psy-Q library functions
that the runtime replaces natively (runtime/hle/hle_functions.txt), keyed by
their address in ACE3.BIN. Same selection rule as tools/recompile.py:
a function whose start address carries a Psy-Q name listed in
hle_functions.txt is taken native.

Inputs are address lists only (recomp/analysis.json, recomp/psyq_symbols.json,
tools/manual_symbols.txt); no game code is read or emitted. Everything else
in the game runs through the MIPS interpreter (runtime/ac3_interp.c).

Usage: python tools/gen_hle_table.py <out.c>
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    out = sys.argv[1]
    analysis = json.load(open(os.path.join(ROOT, 'recomp', 'analysis.json')))
    symbols = {e['addr']: e['name']
               for e in json.load(open(os.path.join(ROOT, 'recomp', 'psyq_symbols.json')))}
    for line in open(os.path.join(ROOT, 'tools', 'manual_symbols.txt')):
        line = line.split('#')[0].strip()
        if line:
            a, n = line.split()
            symbols[int(a, 0)] = n
    hle = {l.split('#')[0].strip() for l in open(os.path.join(ROOT, 'runtime', 'hle', 'hle_functions.txt'))}
    hle.discard('')

    entries = sorted((f['start'], symbols[f['start']]) for f in analysis['functions']
                     if symbols.get(f['start']) in hle)
    with open(out, 'w') as f:
        f.write('/* generated by tools/gen_hle_table.py -- Psy-Q replacements only, no game code */\n')
        f.write('#include "ac3_runtime.h"\n\n')
        for _, n in entries:
            f.write(f'void psyq_{n}(ctx_t *ctx);\n')
        f.write('\nconst struct { u32 addr; ac3_func_t fn; } ac3_func_table[] = {\n')
        for a, n in entries:
            f.write(f'    {{ 0x{a:08X}u, psyq_{n} }},\n')
        f.write('};\n')
        f.write('const unsigned ac3_func_table_len = sizeof(ac3_func_table)/sizeof(ac3_func_table[0]);\n')
        # ac3_prof_dump() reads one counter per table entry: size it to match
        f.write(f'unsigned long long ac3_prof[{max(len(entries), 1)}];\nconst unsigned ac3_prof_len = 0;\n')
    print(f'{len(entries)} Psy-Q replacements -> {out}')


if __name__ == '__main__':
    main()
